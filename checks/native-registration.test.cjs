test('Claude imports only idle matching CLI sessions, confirms native persistence, and never fabricates a desktop record', async t => {
  const f = claudeFixture(t);
  assert.equal(claude.enqueue(f.root, f.agent, f.launch, f.conversations).status, 'waiting-for-desktop');
  let calls = 0;
  const options = { processState: async () => ({ desktopRunning: false, busySessionIds: [] }), openNativeImport: async (_binding, id) => { calls++; assert.equal(id, f.id); } };
  await claude.flush(f.root, options); assert.equal(calls, 0);
  options.processState = async () => ({ desktopRunning: true, busySessionIds: [f.id] });
  await claude.flush(f.root, options); assert.equal(calls, 0);
  options.processState = async () => ({ desktopRunning: true, busySessionIds: [] });
  fs.writeFileSync(f.transcript, JSON.stringify({ sessionId: f.id, cwd: '/wrong' }));
  await claude.flush(f.root, options); assert.equal(calls, 0);
  fs.writeFileSync(f.transcript, JSON.stringify({ sessionId: f.id, cwd: f.agent.workspace }));
  await claude.flush(f.root, options); assert.equal(calls, 1);
  assert.deepEqual(fs.readdirSync(f.sessionsDir), []);
  await claude.flush(f.root, options); assert.equal(calls, 1);
  fs.writeFileSync(path.join(f.sessionsDir, 'local_' + f.id + '.json'), JSON.stringify({ sessionId: 'local_' + f.id, cliSessionId: f.id, cwd: f.agent.workspace, isArchived: false }));
  await claude.flush(f.root, options); assert.equal(calls, 1);
  assert.equal(claude.enqueue(f.root, f.agent, f.launch, f.conversations).status, 'registered');
  assert.equal(JSON.parse(fs.readFileSync(path.join(f.root, 'desktop-sync/claude-pending.json'))).jobs.length, 0);
  assert.equal(require('../standalone/desktop-state.cjs').inspectDesktop(f.agent, { dataDir: f.root, conversations: f.conversations }).status, 'registered');
});

