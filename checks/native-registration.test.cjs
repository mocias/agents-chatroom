test('DSH bridge installs into a clean profile without the Room plugin and invokes native registry', async t => {
  const root = fixture(t), profile = path.join(root, 'profile'); fs.mkdirSync(profile);
  const patch = path.join(profile, 'cordis.patch.yml');
  const original = '- id: other\n  config:\n    untouched: true\n'; fs.writeFileSync(patch, original);
  const workspace = path.join(root, 'agent'); fs.mkdirSync(workspace);
  fs.writeFileSync(path.join(root, 'catalog.json'), JSON.stringify({ agents: [{ id: 'a', backend: 'dsh', workspace, label: 'one' }], conversations: [{ nativeSessions: { a: { backend: 'dsh', id: 'session' } } }] }));
  installBridge(root, {}, { profile });
  const first = fs.readFileSync(patch, 'utf8'); assert.ok(first.startsWith(original));
  assert.match(first, /name: "file:\/\//);
  installBridge(root, {}, { profile }); assert.equal(fs.readFileSync(patch, 'utf8'), first);
  assert.equal((first.match(/id: agent-room-desktop-bridge/g) || []).length, 1);
  const bridge = await import(pathToFileURL(path.join(profile, 'agent-room-desktop-bridge/index.mjs')));
  assert.deepEqual(bridge.inject, ['workspaceRegistry']);
  let dispose, attached;
  bridge.apply({ effect: fn => { dispose = fn(); }, get: () => ({ create: async p => { assert.equal(p, workspace); return { id: 'w', attachSession: async id => { attached = id; } }; } }) }, { nativeCatalogFile: path.join(root, 'catalog.json') });
  await new Promise(resolve => setImmediate(resolve)); dispose();
  assert.equal(attached, 'session');
  assert.equal(JSON.parse(fs.readFileSync(path.join(root, 'desktop-sync/dsh.json'))).agents[0].status, 'registered');
});
test('WorkBuddy registers a real empty native task transactionally, preserves existing rows, and is idempotent', async t => {
  const root = fixture(t), file = path.join(root, 'workbuddy.db');
  const { DatabaseSync } = require('node:sqlite');
  const db = new DatabaseSync(file);
  db.exec(`CREATE TABLE sessions (id TEXT PRIMARY KEY,cwd TEXT NOT NULL,user_id TEXT NOT NULL,title TEXT,custom_title TEXT,status TEXT NOT NULL,created_at INTEGER NOT NULL,updated_at INTEGER NOT NULL,last_activity_at INTEGER,deleted_at INTEGER,is_playground INTEGER NOT NULL DEFAULT 0,source_mode TEXT,mode TEXT,transport TEXT NOT NULL DEFAULT 'local',session_settings TEXT)`);
  db.prepare("INSERT INTO sessions (id,cwd,user_id,status,created_at,updated_at) VALUES ('existing',?,'account','completed',1,1)").run(path.join(root, 'other'));
  db.close();
  const workspace = path.join(root, 'workspace'); fs.mkdirSync(workspace);
  const job = { databaseFile: file, workspace, userId: 'account', taskId: 'registration', title: '工作区登记' };
  assert.equal(await wb.registerTask(job, { running: async () => false }), 'registration');
  assert.equal(await wb.registerTask(job, { running: async () => false }), 'registration');
  const read = new DatabaseSync(file, { readOnly: true });
  assert.equal(read.prepare('SELECT COUNT(*) AS n FROM sessions').get().n, 2);
  const row = read.prepare("SELECT * FROM sessions WHERE id='registration'").get();
  assert.equal(row.status, 'active'); assert.equal(row.mode, 'craft'); assert.equal(row.user_id, 'account');
  assert.equal(read.prepare("SELECT status FROM sessions WHERE id='existing'").get().status, 'completed');
  read.close();
  assert.ok(fs.readdirSync(root).some(n => n.startsWith('workbuddy.db.before-agent-room-')));
  const secondWorkspace = path.join(root, 'second'); fs.mkdirSync(secondWorkspace);
  await assert.rejects(wb.registerTask({ ...job, workspace: secondWorkspace, taskId: 'reopened' }, { running: async () => true }), /重新启动/);
  const verify = new DatabaseSync(file, { readOnly: true });
  assert.equal(verify.prepare("SELECT id FROM sessions WHERE id='reopened'").get(), undefined); verify.close();
});
