test('Codex waits for exit, preserves unrelated state, persists desktop mapping and cancels deleted agents', async t => {
  const root = fixture(t), home = path.join(root, 'codex'); fs.mkdirSync(home);
  const target = path.join(home, '.codex-global-state.json');
  const original = JSON.stringify({ preference: { theme: 'light' }, 'local-projects': { other: { rootPaths: ['/other'] } }, 'project-order': ['other'] });
  fs.writeFileSync(target, original);
  const agent = { id: 'a', label: 'one', backend: 'codex', workspace: path.join(root, 'agent') };
  fs.writeFileSync(path.join(root, 'catalog.json'), JSON.stringify({ agents: [agent] }));
  codex.enqueue(root, agent, 'native', { env: { CODEX_HOME: home } }, [{ nativeSessions: { a: { backend: 'codex', id: 'thread' } } }]);
  assert.equal((await codex.flush(root, { running: async () => true })).status, 'waiting-for-exit');
  assert.equal(fs.readFileSync(target, 'utf8'), original);
  let probes = 0;
  assert.equal((await codex.flush(root, { running: async () => ++probes === 2 })).status, 'waiting-for-exit');
  assert.equal(fs.readFileSync(target, 'utf8'), original);
  assert.equal((await codex.flush(root, { running: async () => false })).status, 'registered');
  const state = JSON.parse(fs.readFileSync(target));
  assert.deepEqual(state.preference, { theme: 'light' });
  assert.deepEqual(state['project-order'], ['other', 'native']);
  assert.equal(state['thread-project-assignments'].thread.projectId, 'native');
  assert.equal(typeof state['local-projects'].native.createdAt, 'number');
  assert.equal(state['app-server-project-id-by-legacy-project-id-by-host']['local:' + home].native, 'native');
  assert.equal((await codex.flush(root, { running: async () => false })).status, 'idle');
  codex.enqueue(root, { ...agent, id: 'deleted' }, 'gone', { env: { CODEX_HOME: home } });
  await codex.flush(root, { running: async () => false });
  assert.equal(JSON.parse(fs.readFileSync(target))['local-projects'].gone, undefined);
  assert.ok(fs.readdirSync(home).some(n => n.includes('.before-agent-room-')));
});
