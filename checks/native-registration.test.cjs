test('Qoder queues until exit, keeps unrelated workspaces, and refuses deleted directories and changed bindings', async t => {
  const root = fixture(t), databaseFile = path.join(root, 'main.sqlite'), workspace = path.join(root, 'agent'); fs.mkdirSync(workspace);
  const { DatabaseSync } = require('node:sqlite');
  const db = new DatabaseSync(databaseFile);
  db.exec(`CREATE TABLE workspaces (workspace_id TEXT PRIMARY KEY,name TEXT NOT NULL,workspace_source TEXT NOT NULL,root_paths_json TEXT NOT NULL,product_mode TEXT NOT NULL DEFAULT 'coding',extra_json TEXT NOT NULL DEFAULT '{}',created_at INTEGER NOT NULL,updated_at INTEGER NOT NULL,archived INTEGER NOT NULL DEFAULT 0,deleted_at INTEGER);
    INSERT INTO workspaces VALUES ('other','Other','local','["/unrelated"]','coding','{}',1,2,0,NULL)`); db.close();
  const agent = { id: 'q', backend: 'qoder', workspace, label: '登记测试' };
  fs.mkdirSync(path.join(root, 'desktop-sync'));
  fs.writeFileSync(path.join(root, 'desktop-sync/bindings.json'), JSON.stringify({ qoder: { databaseFile } }));
  fs.writeFileSync(path.join(root, 'catalog.json'), JSON.stringify({ agents: [agent] }));
  assert.equal(qoder.enqueue(root, agent, {}).status, 'waiting-for-exit');
  const file = path.join(root, 'desktop-sync/qoder-pending.json'), before = fs.readFileSync(file, 'utf8');
  qoder.enqueue(root, agent, {}); assert.equal(fs.readFileSync(file, 'utf8'), before);
  await qoder.flush(root, { running: async () => true });
  let verify = new DatabaseSync(databaseFile); assert.equal(verify.prepare('SELECT COUNT(*) n FROM workspaces').get().n, 1); verify.close();
  let probes = 0;
  await assert.rejects(qoder.flush(root, { running: async () => ++probes === 3 }), /重新启动/);
  await qoder.flush(root, { running: async () => false });
  const result = qoder.enqueue(root, agent, {}); assert.equal(result.status, 'workspace-registered');
  verify = new DatabaseSync(databaseFile);
  assert.equal(verify.prepare('SELECT COUNT(*) n FROM workspaces').get().n, 2);
  assert.equal(verify.prepare("SELECT updated_at FROM workspaces WHERE workspace_id='other'").get().updated_at, 2);
  verify.prepare('UPDATE workspaces SET archived=1 WHERE workspace_id=?').run(result.workspaceId); verify.close();
  assert.throws(() => qoder.enqueue(root, agent, {}), /归档或删除/);
  fs.writeFileSync(file, before); fs.writeFileSync(path.join(root, 'desktop-sync/bindings.json'), JSON.stringify({ qoder: { databaseFile: databaseFile + '.other' } }));
  await assert.rejects(qoder.flush(root, { running: async () => false }), /绑定已变化/);
});

