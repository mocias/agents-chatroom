test('Claude retains a pending previous session when Room opens a replacement session', t => {
  const f = claudeFixture(t), newId = '44444444-4444-4444-8444-444444444444';
  claude.enqueue(f.root, f.agent, f.launch, f.conversations);
  const replacement = [{ nativeSessions: { c: { backend: 'claude', id: newId } } }];
  claude.enqueue(f.root, f.agent, f.launch, replacement);
  const queueFile = path.join(f.root, 'desktop-sync/claude-pending.json');
  assert.deepEqual(new Set(JSON.parse(fs.readFileSync(queueFile)).jobs[0].sessionIds), new Set([f.id, newId]));
  fs.writeFileSync(path.join(f.sessionsDir, 'local_' + f.id + '.json'), JSON.stringify({ sessionId: 'local_' + f.id, cliSessionId: f.id, cwd: f.agent.workspace, isArchived: false }));
  assert.equal(claude.enqueue(f.root, f.agent, f.launch, replacement).workspaceRegistered, true);
  assert.equal(require('../standalone/desktop-state.cjs').inspectDesktop(f.agent, { dataDir: f.root, conversations: replacement }).workspaceRegistered, true);
  assert.equal(JSON.parse(fs.readFileSync(queueFile)).jobs[0].sessionIds.length, 1);
});
